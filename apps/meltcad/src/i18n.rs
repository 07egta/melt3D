fn table(lang: &str) -> Table {
    match lang {
        "en" => EN,
        "zh-Hans" => ZH_HANS,
        "ko" => KO,
        "de" => DE,
        "fr" => FR,
        "es" => ES,
        _ => JA,
    }
}

fn lookup(lang: &str, key: &str) -> Option<&'static str> {
    table(lang).iter().find(|(id, _)| *id == key).map(|(_, text)| *text)
}

/// Translate `key` into the current language. Missing entries fall back to Japanese, then to
/// the key itself, so text is never blank and an unknown id cannot crash a frame.
pub fn tr(key: &str) -> &str {
    let lang = crate::prefs::current_lang();
    lookup(lang, key).or_else(|| lookup("ja", key)).unwrap_or(key)
}

